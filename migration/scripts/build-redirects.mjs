// Builds public/_redirects (the file Cloudflare reads) from two sources:
//
//   1. migration/redirects/webflow-301.csv   the redirects that already existed in Webflow
//   2. the redirects this migration adds     (listed below)
//
// Chains are flattened, so /a -> /b -> /c becomes /a -> /c: one hop for visitors and search engines.
// A redirect whose address is now a real page on the new site is left out and reported.
//
// Run after `npm run build`:  node migration/scripts/build-redirects.mjs

import { access, readFile, writeFile } from "node:fs/promises";

const ADDED = [
  // Foodie guides and map guides now share one page.
  ["/map-guides-itineraries", "/articles"],
  ["/map-guides", "/articles"],
  // Webflow's search results page has no equivalent on the new site.
  ["/search", "/"],
  // The old redirects pointed these at /vegan-product-reviews, a page that no longer exists.
  ["/vegan-product-reviews", "/articles?category=products-and-shopping"],
];

const csv = await readFile("migration/redirects/webflow-301.csv", "utf8");
const rules = new Map();
for (const line of csv.split(/\r?\n/).slice(1)) {
  if (!line.trim()) continue;
  const comma = line.indexOf(",");
  let source = line.slice(0, comma).trim();
  let target = line.slice(comma + 1).trim();
  // Cloudflare redirects can't match on a query string; /restaurants -> / already covers this one.
  if (source.includes("?")) continue;
  // Webflow's wildcard syntax (/blog%-posts/(.*) -> /articles/%1) in Cloudflare's (/blog-posts/* -> /articles/:splat).
  source = source.replace(/%-/g, "-").replace(/\(\.\*\)/g, "*");
  target = target.replace(/%1/g, ":splat");
  rules.set(source, target);
}
for (const [source, target] of ADDED) rules.set(source, target);

// Follow each target until it stops being redirected itself.
const resolve = (target, seen = new Set()) => {
  const next = rules.get(target.split("?")[0]);
  if (!next || seen.has(target)) return target;
  seen.add(target);
  return resolve(next, seen);
};

const exists = async (path) => {
  const file = path === "/" ? "dist/index.html" : `dist${path}.html`;
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
};

const lines = [
  "# Redirects, read by Cloudflare. Generated by migration/scripts/build-redirects.mjs.",
  "# Format: old address, new address, status code.",
  "",
];
const skipped = [];
const missing = [];
for (const [source, firstTarget] of [...rules].sort(([a], [b]) => a.localeCompare(b))) {
  const target = resolve(firstTarget);
  if (!source.includes("*") && (await exists(source))) {
    skipped.push(source);
    continue;
  }
  if (!target.includes(":splat") && !(await exists(target.split("?")[0]))) missing.push(`${source} -> ${target}`);
  lines.push(`${source} ${target} 301`);
}
await writeFile("public/_redirects", lines.join("\n") + "\n");

console.log(`${lines.length - 3} redirects written to public/_redirects`);
if (skipped.length) console.log(`Left out because the address is a real page now: ${skipped.join(", ")}`);
if (missing.length) console.log(`WARNING: these point at a page that isn't built:\n  ${missing.join("\n  ")}`);
